import {createRequire} from 'node:module';
import {mkdirSync} from 'node:fs';
import {homedir} from 'node:os';
import {join} from 'node:path';
const require=createRequire(new URL('../../frontend/package.json',import.meta.url));
const {chromium,expect}=require('@playwright/test');
const browser=await chromium.launch({executablePath:join(homedir(),'.cache/ms-playwright/chromium_headless_shell-1234/chrome-headless-shell-linux64/chrome-headless-shell'),headless:true,args:['--no-sandbox','--enable-unsafe-swiftshader','--use-angle=swiftshader']});
try {
const page=await browser.newPage({baseURL:process.env.P1_API ?? 'http://127.0.0.1:8002',viewport:{width:1440,height:900}});
  const errors = [];
  page.on('console', message => { if (message.type() === 'error') { errors.push(message.text()); console.log('Browser error:', message.text()); } });
  page.on('pageerror', error => { errors.push(error.message); console.log('Page error:', error.message); });
  await page.goto('/viewer-demo', { waitUntil: 'domcontentloaded', timeout: 60_000 });
  const viewport = page.getByTestId('viewport');
  await expect(viewport).toHaveAttribute('data-rendered', 'true', { timeout: 60_000 });
  await expect(viewport).toHaveAttribute('data-backend', 'webgl2');
  await expect(page.getByTestId('inspector')).toContainText('object-01');
  await expect(page.getByTestId('inspector')).toContainText('[22,0,2.5]');
  mkdirSync('tests/platform/screenshots', { recursive: true });
  await page.waitForTimeout(1500);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: 'tests/platform/screenshots/viewer-demo-orbit.png' });
  await page.getByRole('button', { name: 'Play', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Pause', exact: true })).toBeVisible();
  await page.waitForTimeout(750);
  await page.getByRole('button', { name: 'Pause', exact: true }).click();
  await page.getByRole('combobox', { name: 'Camera mode' }).press('Enter');
  await page.getByRole('combobox', { name: 'Camera mode' }).press('ArrowDown');
  await page.getByRole('combobox', { name: 'Camera mode' }).press('Enter');
  await expect(page.getByText('Follow', { exact: true }).first()).toBeVisible();
  await page.waitForTimeout(2000);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: 'tests/platform/screenshots/viewer-demo-follow.png' });
  await page.getByRole('combobox', { name: 'Entity', exact: true }).press('Enter');
  await page.getByRole('combobox', { name: 'Entity', exact: true }).fill('record-1');
  await page.getByRole('combobox', { name: 'Entity', exact: true }).press('ArrowDown');
  await page.getByRole('combobox', { name: 'Entity', exact: true }).press('Enter');
  await expect(page.getByTestId('inspector')).toContainText('scheduled');
  await expect(page.getByTestId('inspector')).not.toContainText('Position');
  await page.getByRole('combobox', { name: 'Language' }).press('Enter');
  await page.getByRole('combobox', { name: 'Language' }).press('ArrowDown');
  await page.getByRole('combobox', { name: 'Language' }).press('Enter');
  await expect(page.getByText('实体检查器', { exact: true })).toBeVisible();
  await expect(page.getByText('精确的已提交值。显示插值不会更改这些事实。')).toBeVisible();
  expect(errors).toEqual([]);
console.log(JSON.stringify({demo:'passed',errors}));
} finally {await browser.close();}

def test_outside_outside_crossing_is_detected_without_tunneling() -> None:
    zone = _zone(zone_id="nfz.cross")
    samples = (
        _sample("s0", 0.0, -60.0, 10.0, 0.0),
        _sample("s1", 10.0, 60.0, 10.0, 0.0),
    )
    report = detect_no_fly_events(zone, samples, subject_id="aircraft.1")
    assert report.violation_count == 1
    event = report.violations[0]
    assert event.event_type == "observed_entry"
    assert event.start_basis == "interpolated_crossing"
    assert event.end_basis == "interpolated_crossing"
    assert event.start_inferred is True
    assert event.end_inferred is True
    assert event.bound_start_sample_ref == "s0"
    assert event.bound_end_sample_ref == "s1"
    # X=-20 -> X=+20 maps linearly onto the 10 s segment: [10/3, 20/3].
    assert event.start_time_s == pytest.approx(10.0 / 3.0)
    assert event.end_time_s == pytest.approx(20.0 / 3.0)
    assert report.interpolation_assumed is True
    assert report.body_clearance == "none"



def test_deterministic_event_ids_and_evidence_refs() -> None:
    zone = _zone(zone_id="nfz.det")
    samples = (
        _sample("a0", 0.0, -60.0, 10.0, 0.0),
        _sample("a1", 10.0, 60.0, 10.0, 0.0),
    )
    first = detect_no_fly_events(zone, samples, subject_id="aircraft.1")
    second = detect_no_fly_events(zone, samples, subject_id="aircraft.1")
    assert first == second
    for event in first.violations:
        assert len(event.event_id) == 64
        assert all(character in "0123456789abcdef" for character in event.event_id)
        assert event.bound_start_sample_ref in {"a0", "a1"}
        assert event.bound_end_sample_ref in {"a0", "a1"}
    ids = [event.event_id for event in first.violations]
    assert len(ids) == len(set(ids))



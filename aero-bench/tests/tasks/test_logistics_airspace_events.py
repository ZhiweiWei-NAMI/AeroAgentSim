"""Module-level tests for the bounded selected-city no-fly violation detector.

The detector is a narrow pure domain component: strict lowering of the
current authoring zone shape into a canonical framed input, then
deterministic violation detection from caller-supplied authoritative position
samples. Tests here are real mathematical cases with positional and temporal
values chosen by hand; no sample is generated by the code under test.
"""

from __future__ import annotations

import math

import pytest
from pydantic import ValidationError

from aero_bench.tasks.logistics.airspace_events import (
    NO_FLY_FRAME,
    AuthoredNoFlyZone,
    NoFlyEventsReport,
    NoFlyZone,
    PositionSample,
    compile_no_fly_zone,
    compile_no_fly_zones,
    detect_no_fly_events,
)


def _square(half: float = 20.0) -> list[dict[str, float]]:
    return [
        {"x": -half, "z": -half},
        {"x": half, "z": -half},
        {"x": half, "z": half},
        {"x": -half, "z": half},
    ]


def _zone(
    *,
    zone_id: str = "nfz.1",
    name: str = "test-zone",
    polygon: object | None = None,
    floor: float = 0.0,
    ceiling: float = 50.0,
    starts: float = 0.0,
    ends: float | None = None,
) -> NoFlyZone:
    return NoFlyZone.model_validate(
        {
            "zone_id": zone_id,
            "name": name,
            "frame": NO_FLY_FRAME,
            "polygon": _square() if polygon is None else polygon,
            "floor_m": floor,
            "ceiling_m": ceiling,
            "starts_at_s": starts,
            "ends_at_s": ends,
            "source": {"kind": "manual", "label": "test", "uri": None},
        }
    )


def _sample(
    ref: str, time_s: float, x: float, y: float, z: float
) -> PositionSample:
    return PositionSample(
        sample_ref=ref, time_s=time_s, x=x, y=y, z=z
    )


def test_lowering_accepts_current_authoring_shape_and_attaches_frame() -> None:
    raw = {
        "id": "nfz.hospital",
        "name": "hospital",
        "polygon": [{"x": -50, "z": -50}, {"x": 50, "z": -50}, {"x": 50, "z": 50}, {"x": -50, "z": 50}],
        "floorM": 0,
        "ceilingM": 120,
        "startsAtS": 0,
        "endsAtS": None,
        "source": {"kind": "geojson", "label": "import", "uri": "asset://nfz"},
    }
    lowered = compile_no_fly_zone(raw)
    assert lowered.zone_id == "nfz.hospital"
    assert lowered.frame == NO_FLY_FRAME
    assert lowered.floor_m == 0.0
    assert lowered.ceiling_m == 120.0
    assert lowered.starts_at_s == 0.0
    assert lowered.ends_at_s is None
    assert lowered.source.kind == "geojson"
    assert len(lowered.polygon) == 4
    assert compile_no_fly_zones([raw])[0] == lowered



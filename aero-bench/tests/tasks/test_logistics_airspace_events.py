# Independent regressions for the boundary-touch and activation-naming defects
# found by the WorkBuddy review. Expectations are hand-computed with strict
# interior and half-open-window semantics; they do not reuse detection logic.


def test_boundary_touch_with_bounded_window_ends_at_touch_not_window_expiry() -> None:
    """B1: a measured sample exactly on the polygon edge ends the violation
    there even when the bounded window's scheduled expiry is much later."""
    zone = _zone(zone_id="nfz.reg-b1", starts=0.0, ends=100.0)
    samples = (
        _sample("s0", 0.0, -10.0, 10.0, 0.0),
        _sample("s1", 10.0, 20.0, 10.0, 0.0),  # exactly on the right edge x=20
        _sample("s2", 20.0, 60.0, 10.0, 0.0),  # clearly outside afterwards
    )
    report = detect_no_fly_events(zone, samples, subject_id="aircraft.1")
    assert report.violation_count == 1
    event = report.violations[0]
    # Strict interior makes the airframe leave the open volume at the measured
    # boundary sample (t=10), not at the scheduled window expiry (t=100).
    assert event.event_type == "already_inside"
    assert event.start_basis == "initial_sample"
    assert event.start_time_s == 0.0
    assert event.end_time_s == 10.0
    assert event.end_basis == "sample_boundary_touch"
    assert event.end_basis != "time_window_expiry"
    assert event.end_inferred is False
    assert event.bound_end_sample_ref == "s1"


def test_boundary_touch_unbounded_window_is_not_an_interpolated_crossing() -> None:
    """B2: the same measured boundary touch, unbounded window, must not be
    marked interpolated/inferred: the endpoint is the measured sample itself."""
    zone = _zone(zone_id="nfz.reg-b2")
    samples = (
        _sample("s0", 0.0, -10.0, 10.0, 0.0),
        _sample("s1", 10.0, 20.0, 10.0, 0.0),  # exactly on the right edge x=20
        _sample("s2", 20.0, 60.0, 10.0, 0.0),  # clearly outside afterwards
    )
    report = detect_no_fly_events(zone, samples, subject_id="aircraft.1")
    assert report.violation_count == 1
    event = report.violations[0]
    assert event.end_time_s == 10.0
    assert event.end_basis == "sample_boundary_touch"
    assert event.end_basis != "interpolated_crossing"
    assert event.end_inferred is False
    assert event.bound_end_sample_ref == "s1"


def test_boundary_touch_then_reentry_is_two_maximal_intervals() -> None:
    """B4 split: touching the boundary at a measured sample interrupts the open
    interior, so the re-entry afterwards is a distinct maximal interval."""
    zone = _zone(zone_id="nfz.reg-b4", starts=0.0, ends=100.0)
    samples = (
        _sample("s0", 0.0, -10.0, 10.0, 0.0),
        _sample("s1", 10.0, 20.0, 10.0, 0.0),  # exactly on the right edge x=20
        _sample("s2", 20.0, 10.0, 10.0, 0.0),  # inside again
    )
    report = detect_no_fly_events(zone, samples, subject_id="aircraft.1")
    assert report.violation_count == 2
    leaving, reentry = report.violations
    assert leaving.event_type == "already_inside"
    assert leaving.start_time_s == 0.0
    assert leaving.end_time_s == 10.0
    assert leaving.end_basis == "sample_boundary_touch"
    assert leaving.end_inferred is False
    assert leaving.bound_end_sample_ref == "s1"
    assert reentry.start_time_s == 10.0
    assert reentry.end_time_s == 20.0
    assert reentry.start_basis == "sample_endpoint"
    assert reentry.start_inferred is False
    assert reentry.end_basis == "stream_end"
    assert len({event.event_id for event in report.violations}) == 2



def test_concave_polygon_multiple_entries_in_one_segment() -> None:
    concave = [
        {"x": -10, "z": -10}, {"x": 10, "z": -10}, {"x": 10, "z": 10},
        {"x": 5, "z": 10}, {"x": 5, "z": 0}, {"x": -5, "z": 0},
        {"x": -5, "z": 10}, {"x": -10, "z": 10},
    ]
    zone = _zone(zone_id="nfz.u", polygon=concave)
    samples = (
        _sample("s0", 0.0, -20.0, 10.0, 5.0),
        _sample("s1", 10.0, 20.0, 10.0, 5.0),
    )
    report = detect_no_fly_events(zone, samples, subject_id="aircraft.1")
    assert report.violation_count == 2
    left, right = report.violations
    assert left.event_type == "observed_entry"
    assert right.event_type == "observed_entry"
    assert left.start_basis == "interpolated_crossing"
    assert left.end_basis == "interpolated_crossing"
    assert left.start_time_s == pytest.approx(2.5)
    assert left.end_time_s == pytest.approx(3.75)
    assert right.start_time_s == pytest.approx(6.25)
    assert right.end_time_s == pytest.approx(7.5)
    assert left.bound_start_sample_ref == "s0"
    assert left.bound_end_sample_ref == "s1"
    assert right.bound_start_sample_ref == "s0"
    assert right.bound_end_sample_ref == "s1"
    assert len({event.event_id for event in report.violations}) == 2



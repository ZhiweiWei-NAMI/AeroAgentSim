def test_pbr_check_rejects_the_invalid_key() -> None:
    """Negative control: the non-spec key must be flagged, not ignored."""

    doc, _binary, _stats = validate.parse_glb(
        VALIDATION_DIR / _manifest()["buildings"][0]["glb"]
    )
    materials = copy.deepcopy(doc["materials"])
    assert validate._pbr_problems(materials) == []

    materials[0]["pbrMetallicRoughness"]["metallicRoughnessFactor"] = [0.0, 0.5]
    problems = validate._pbr_problems(materials)
    assert any("metallicRoughnessFactor" in p for p in problems)

    materials = copy.deepcopy(doc["materials"])
    materials[0]["pbrMetallicRoughness"]["metallicFactor"] = 1.0
    problems = validate._pbr_problems(materials)
    assert any("metallicFactor" in p for p in problems)

    materials = copy.deepcopy(doc["materials"])
    materials[1]["pbrMetallicRoughness"]["roughnessFactor"] = 1.0
    problems = validate._pbr_problems(materials)
    assert any("roughnessFactor" in p for p in problems)



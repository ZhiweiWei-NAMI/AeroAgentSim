def test_non_simple_footprints_are_rejected() -> None:
    open_ring = [(0.0, 0.0), (10.0, 0.0), (10.0, 10.0), (0.0, 10.0)]
    with pytest.raises(gen.ScaleoutError, match="non_simple_polygon"):
        gen.validate_footprint("test.open", open_ring)

    spike = [(0.0, 0.0), (10.0, 0.0), (10.0, 10.0), (5.0, -4.0), (0.0, 10.0), (0.0, 0.0)]
    with pytest.raises(gen.ScaleoutError, match="non_simple_polygon"):
        gen.validate_footprint("test.spike", spike)

    bowtie = [(0.0, 0.0), (10.0, 10.0), (10.0, 0.0), (0.0, 10.0), (0.0, 0.0)]
    with pytest.raises(gen.ScaleoutError, match="non_simple_polygon"):
        gen.validate_footprint("test.bowtie", bowtie)

    duplicate = [(0.0, 0.0), (10.0, 0.0), (0.0, 0.0), (10.0, 10.0), (0.0, 0.0)]
    with pytest.raises(gen.ScaleoutError, match="non_simple_polygon"):
        gen.validate_footprint("test.duplicate", duplicate)

    # the validator's independent detector agrees
    assert validate._footprint_simple(spike)[0] is False
    assert validate._footprint_simple(bowtie)[0] is False
    assert validate._footprint_simple(open_ring)[0] is False
    assert validate._footprint_simple([(0.0, 0.0), (10.0, 0.0), (10.0, 10.0), (0.0, 10.0), (0.0, 0.0)])[0] is True

    # every real footprint passes both detectors
    for building in _objects()["buildings"]:
        ring = [tuple(p) for p in building["footprint_enu_m"]]
        gen.validate_footprint(building["object_id"], ring)
        assert validate._footprint_simple(ring)[0] is True



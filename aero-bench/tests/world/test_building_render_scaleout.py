"""Tests for the 414-building render scale-out and its fail-closed policy.

Subjects (checked-in artifacts under
``validation/building-render-scaleout-mimo-20260929/``):

  * the standalone validator must pass every check, including a full
    byte-identical regeneration into a temp sandbox;
  * exactly one GLB exists per ``object_id`` for all 414 buildings, and the
    catalog fragment pins each one's real sha256 under the strict
    ``CatalogBuildingRender`` contract (glTF content is ``asset_local``;
    a WGS84 label is rejected);
  * the style/atlas policy is deterministic for any input order and only
    ever uses styles that survived the seam audit;
  * the fail-closed paths really fail: non-simple polygons, missing
    texture/material, size mismatch and count mismatch all raise instead of
    skipping a building.

No fake GLBs are used anywhere: every generated byte in these tests comes
from the real BigCity atlases and the real compiled-scene footprints.
"""

from __future__ import annotations


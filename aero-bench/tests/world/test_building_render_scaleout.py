        assert extras["style"]["region_px"] == style["region_px"]
        assert extras["style"]["wrap_seam_ratio"] == style["wrap_seam_ratio"]
        assert extras["style"]["assignment"]["height_class"] == expect["height_class"]
        assert extras["style"]["assignment"]["pool_index"] == expect["pool_index"]
        assert extras["style"]["assignment"]["rule"] == gen.ASSIGNMENT_RULE
        assert extras["source_frame"] == "asset_local"
        assert doc["nodes"][0]["name"] == object_id



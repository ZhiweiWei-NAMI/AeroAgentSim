def test_only_audited_styles_are_used(styles: dict) -> None:
    manifest = _manifest()
    usage = manifest["style_usage"]
    audit = {r["style_id"]: r for r in manifest["style_audit"]}
    assert manifest["totals"]["styles_used"] == sum(1 for c in usage.values() if c)
    for style_id, count in usage.items():
        assert count > 0
        assert audit[style_id]["status"] == "accepted"
        assert style_id in styles
        assert audit[style_id]["wrap_seam_ratio"] <= gen.GATES["seam_ratio_max"]
    # the rejected cell is recorded, never referenced by any building
    rejected = [s for s, r in audit.items() if r["status"] == "rejected"]
    assert rejected, "expected at least one cell to fail the seam audit by design"
    for style_id in rejected:
        assert style_id not in usage
        for record in manifest["buildings"]:
            assert record["style_id"] != style_id



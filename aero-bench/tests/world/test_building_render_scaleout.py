def test_size_mismatch_fails_closed() -> None:
    building = _sample_building()
    ring = [tuple(p) for p in building["footprint_enu_m"]]
    sdf_text = validate.SDF_PATH.read_text(encoding="utf-8")
    sdf = validate._sdf_entry(sdf_text, building["object_id"])
    base = float(building["base_enu_up_m"])
    top = float(building["top_enu_up_m"])

    doc, binary, _stats = validate.parse_glb(
        VALIDATION_DIR / f"assets/{building['object_id']}.glb"
    )
    positions = validate._gltf_positions(doc, binary)
    mins, maxs = validate._bbox(positions)

    # ground truth agrees
    assert validate._bbox_problems(
        building["object_id"], ring, base, top, sdf, mins, maxs
    ) == []
    gen.cross_check_bbox(building["object_id"], building, sdf, (mins, maxs))

    # a 5 cm taller GLB must be rejected
    scaled_maxs = list(maxs)
    scaled_maxs[1] += 0.05
    problems = validate._bbox_problems(
        building["object_id"], ring, base, top, sdf, mins, scaled_maxs
    )
    assert problems and any("Y/top" in p for p in problems)
    with pytest.raises(gen.ScaleoutError, match="size_mismatch"):
        gen.cross_check_bbox(
            building["object_id"], building, sdf, (mins, scaled_maxs)
        )

    # an SDF collision that disagrees with objects.json must be rejected
    bad_sdf = dict(sdf)
    bad_sdf["height"] = sdf["height"] + 0.05
    problems = validate._bbox_problems(
        building["object_id"], ring, base, top, bad_sdf, mins, maxs
    )
    assert problems and any("SDF height" in p for p in problems)
    with pytest.raises(gen.ScaleoutError, match="size_mismatch"):
        gen.cross_check_bbox(building["object_id"], building, bad_sdf, (mins, maxs))

    # a footprint whose polyline drifted must be rejected
    bad_sdf = dict(sdf)
    drift = list(sdf["points"])
    drift[0] = (drift[0][0] + 0.05, drift[0][1])
    bad_sdf["points"] = drift
    problems = validate._bbox_problems(
        building["object_id"], ring, base, top, bad_sdf, mins, maxs
    )
    assert problems and any("polyline" in p for p in problems)


def test_count_mismatch_fails_closed(tmp_path, monkeypatch) -> None:
    """A scene that is not 414 buildings aborts before any GLB is written."""

    monkeypatch.setattr(gen, "EXPECTED_BUILDING_COUNT", 413)
    with pytest.raises(gen.ScaleoutError, match="count_mismatch"):
        gen.generate(tmp_path / "assets", artifact_dir=tmp_path)
    assets = tmp_path / "assets"
    assert (list(assets.glob("*.glb")) if assets.exists() else []) == []
    # checked-in artifacts are untouched (the run wrote into the sandbox)
    assert json.loads(gen.EXCEPTIONS_PATH.read_text(encoding="utf-8"))[
        "exception_count"
    ] == 0



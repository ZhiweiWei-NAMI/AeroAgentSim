def test_exactly_one_glb_per_object_id() -> None:
    objects = _objects()
    manifest = _manifest()
    records = manifest["buildings"]
    scene_ids = {b["object_id"] for b in objects["buildings"]}
    record_ids = [r["object_id"] for r in records]

    assert len(scene_ids) == 414
    assert len(record_ids) == 414
    assert len(set(record_ids)) == 414
    assert set(record_ids) == scene_ids

    on_disk = {p.stem for p in ASSET_DIR.glob("*.glb")}
    assert on_disk == scene_ids
    assert len(on_disk) == 414

    for record in records:
        path = VALIDATION_DIR / record["glb"]
        assert path.name == f"{record['object_id']}.glb"
        assert path.stat().st_size == record["glb_bytes"]



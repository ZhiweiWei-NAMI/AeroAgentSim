def test_assignment_is_order_independent(styles: dict) -> None:
    buildings = _objects()["buildings"]
    baseline = gen.assign_styles(buildings, styles)
    assert len(baseline) == 414
    for permutation in (
        list(reversed(buildings)),
        sorted(buildings, key=lambda b: b["object_id"], reverse=True),
        sorted(buildings, key=lambda b: b["object_id"]),
    ):
        assert gen.assign_styles(permutation, styles) == baseline
    # and it matches the manifest for every building
    for record in _manifest()["buildings"]:
        expect = baseline[record["object_id"]]
        assert record["style_id"] == expect["style_id"]
        assert record["height_class"] == expect["height_class"]



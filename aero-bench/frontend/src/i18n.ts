const DICTS: Readonly<Record<Language, Readonly<Record<I18nKey, string>>>> = { zh, en };

let current: Language = DEFAULT_LANGUAGE;

const listeners = new Set<(language: Language) => void>();

function storedLanguage(): Language {
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    return stored === "en" ? "en" : DEFAULT_LANGUAGE;
  } catch {
    return DEFAULT_LANGUAGE;
  }
}

/** Initialize from storage; safe to call repeatedly. */
export function initLanguage(): Language {
  current = storedLanguage();
  return current;
}

export function currentLanguage(): Language {
  return current;
}

export function setLanguage(language: Language): void {
  if (!LANGUAGES.includes(language) || language === current) {
    return;
  }
  current = language;
  try {
    window.localStorage.setItem(STORAGE_KEY, language);
  } catch {
    // Storage may be unavailable; the in-memory language still applies.
  }
  for (const listener of [...listeners]) {
    listener(language);
  }
}

export function subscribeLanguage(listener: (language: Language) => void): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

export function t(key: I18nKey, language: Language = current): string {
  return DICTS[language][key];
}

/** Translate with {placeholder} interpolation. */
export function tf(
  key: I18nKey,
  params: Readonly<Record<string, string | number>>,
  language: Language = current,
): string {
  let text: string = DICTS[language][key];
  for (const [name, value] of Object.entries(params)) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}
